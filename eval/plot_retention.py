"""Render the stress-test retention chart from a results JSON.

Produces a two-panel matplotlib figure:
  - Left: recall vs. context-overflow factor, one line per system.
  - Right: recall vs. needle position (early / mid / late thirds of the stream)
    at the heaviest distractor sweep, one line per system.

The left panel is the readme hero chart; the right panel illustrates FIFO's
signature failure mode (it loses *early* needles specifically).
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


_SYSTEM_STYLE = {
    "ours": {"label": "Ours (novelty-scored)", "color": "#1f77b4", "marker": "o"},
    "fifo": {"label": "MemGPT-style FIFO", "color": "#d62728", "marker": "s"},
}


def _load(path: Path) -> dict:
    with open(path) as f:
        return json.load(f)


def _recall_by_distractors(rows: list[dict]) -> dict[str, dict[int, tuple[float, float]]]:
    """Group rows by (system, n_distractors) and compute mean recall + stderr."""
    bucket: dict[tuple[str, int], list[bool]] = defaultdict(list)
    for r in rows:
        bucket[(r["system"], r["n_distractors"])].append(r["found"])
    out: dict[str, dict[int, tuple[float, float]]] = defaultdict(dict)
    for (system, n), founds in bucket.items():
        arr = np.array(founds, dtype=np.float32)
        mean = float(arr.mean())
        stderr = float(arr.std(ddof=0) / np.sqrt(len(arr))) if len(arr) > 1 else 0.0
        out[system][n] = (mean, stderr)
    return out


def _recall_by_position_thirds(rows: list[dict], n_distractors: int) -> dict[str, list[float]]:
    """Bucket needles into [early, mid, late] thirds of the stream and average recall."""
    filtered = [r for r in rows if r["n_distractors"] == n_distractors]
    out: dict[str, list[float]] = {}
    for system in ("ours", "fifo"):
        sys_rows = [r for r in filtered if r["system"] == system]
        if not sys_rows:
            out[system] = [0.0, 0.0, 0.0]
            continue
        stream_len = max(r["stream_len"] for r in sys_rows)
        thirds = [[], [], []]
        for r in sys_rows:
            third = min(2, int(r["stream_pos"] / max(1, stream_len) * 3))
            thirds[third].append(float(r["found"]))
        out[system] = [
            float(np.mean(t)) if t else 0.0 for t in thirds
        ]
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, help="Stress-test JSON path.")
    parser.add_argument("--out", required=True, help="Output PNG path.")
    parser.add_argument(
        "--title",
        default="Memory retention under sequential overflow",
    )
    args = parser.parse_args()

    data = _load(Path(args.input))
    rows = data["results"]
    config = data["config"]
    max_tokens = config["max_tokens"]

    grouped = _recall_by_distractors(rows)
    heaviest = max(config["distractors_sweep"])
    thirds = _recall_by_position_thirds(rows, heaviest)

    # Approximate overflow factor: assume ~10 tokens per item (needles + distractors
    # generated by the harness all sit around that length). The plot legend states
    # this assumption explicitly so it's not load-bearing for the conclusion.
    approx_tokens_per_item = 10

    fig, (ax_left, ax_right) = plt.subplots(1, 2, figsize=(12, 5))

    # ---- Left panel: recall vs overflow factor ----
    for system, by_n in grouped.items():
        ns = sorted(by_n.keys())
        means = [by_n[n][0] for n in ns]
        stderrs = [by_n[n][1] for n in ns]
        overflow = [
            (n + config["needles"]) * approx_tokens_per_item / max_tokens for n in ns
        ]
        style = _SYSTEM_STYLE[system]
        ax_left.errorbar(
            overflow, means, yerr=stderrs,
            label=style["label"], color=style["color"], marker=style["marker"],
            linewidth=2, markersize=7, capsize=3,
        )
    ax_left.axvline(1.0, color="gray", linestyle=":", alpha=0.6, label="Budget boundary")
    ax_left.set_xlabel(f"Context overflow factor  (stream tokens / {max_tokens}-token budget)")
    ax_left.set_ylabel("Recall@1")
    ax_left.set_ylim(-0.05, 1.05)
    ax_left.set_title("Needle recall vs. stream overflow")
    ax_left.legend(loc="lower left")
    ax_left.grid(alpha=0.3)

    # ---- Right panel: recall vs position bucket at heaviest sweep ----
    positions = ["Early third", "Middle third", "Late third"]
    x = np.arange(len(positions))
    width = 0.35
    for i, (system, vals) in enumerate(thirds.items()):
        style = _SYSTEM_STYLE[system]
        ax_right.bar(
            x + (i - 0.5) * width, vals, width,
            label=style["label"], color=style["color"], alpha=0.85,
        )
    ax_right.set_xticks(x, positions)
    ax_right.set_ylabel("Recall@1")
    ax_right.set_ylim(0, 1.05)
    ax_right.set_title(f"Recall by needle position (at {heaviest} distractors)")
    ax_right.legend(loc="lower right")
    ax_right.grid(alpha=0.3, axis="y")

    fig.suptitle(args.title, fontsize=14, fontweight="bold")
    fig.tight_layout()
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=140, bbox_inches="tight")
    print(f"[plot_retention] wrote {out_path}")


if __name__ == "__main__":
    main()
